const LANGS = ["en", "fr"];

function chosen() {
  const asked = new URLSearchParams(location.search).get("lang");
  if (LANGS.includes(asked)) return asked;
  try {
    const saved = localStorage.getItem("lang");
    if (LANGS.includes(saved)) return saved;
  } catch {}
  return navigator.language.startsWith("fr") ? "fr" : "en";
}

export const lang = chosen();
document.documentElement.lang = lang;

export const t = (text, vars = {}) =>
  (lang === "fr" ? FR[text] ?? text : text).replace(/\{(\w+)\}/g, (_, key) => vars[key]);

// The language sits in the query string so a French link stays French when shared.
export function switchLang(next) {
  try {
    localStorage.setItem("lang", next);
  } catch {}
  const search = new URLSearchParams(location.search);
  search.set("lang", next);
  location.assign(`${location.pathname}?${search}${location.hash}`);
}

